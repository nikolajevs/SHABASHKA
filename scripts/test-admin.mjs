import assert from 'node:assert/strict';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:5174';
if(!['127.0.0.1','localhost'].includes(new URL(origin).hostname))throw Error('Local Worker only');
const prefix='admin-test-'+Date.now();
const admin={id:prefix+'-admin',email:process.env.TEST_ADMIN_EMAIL||'seedy@sites.test'};
const customer={id:prefix+'-customer',email:'customer@example.test'},provider={id:prefix+'-provider',email:'provider@example.test'};
let checks=0;
async function req(path,user,body,status=200,extra={}){
 const headers={Connection:'close',...(user?{'oai-authenticated-user-id':user.id,'oai-authenticated-user-email':user.email}:{}),...(body?{Origin:origin,'Content-Type':'application/json'}:{}),...extra};
 const r=await fetch(origin+path,{method:body?'POST':'GET',headers,body:body?JSON.stringify(body):undefined});
 const result=await r.json();assert.equal(r.status,status,JSON.stringify(result));checks++;return result;
}
const market=(u,b,s)=>req('/api/market',u,b,s),manage=(b,s)=>req('/api/admin',admin,b,s);
await req('/api/admin',null,undefined,401);
await req('/api/admin',customer,undefined,403);
await req('/api/admin',customer,{action:'restore',id:'anything',reason:'test'},403);
await req('/api/admin',null,{action:'restore'},401);
await req('/api/admin',admin,{action:'restore'},403,{Origin:'https://unrelated.example'});
await req('/api/admin?kind=message',admin,undefined,400);
await req('/api/admin?page=1.5',admin,undefined,400);
await market(admin,{action:'register',name:prefix+' админ',role:'customer'});
await market(customer,{action:'register',name:prefix+' заказчик',role:'customer',isAdmin:true});
await market(provider,{action:'register',name:prefix+' исполнитель',role:'provider'});
assert.equal((await market(customer)).user.isAdmin,false);checks++;
assert.equal((await market(admin)).user.isAdmin,true);checks++;
await manage({action:'restrict',id:'account:'+admin.id,reason:'self block'},400);
await manage({action:'restrict',id:'missing',reason:'not found'},404);
await manage({action:'restrict',id:'account:'+customer.id,reason:''},400);

const restore=id=>manage({action:'restore',id,reason:'Проверка восстановления'});
await restrict(task.id);
assert.ok(!(await market(null)).records.some(r=>r.id===task.id));checks++;
await market(provider,{action:'bid',parent:task.id,description:'Готов',price:'40 €'},403);
await market(customer,{action:'choose',id:bid.id},403);
await market(provider,{action:'message',parent:bid.id,description:'Нельзя'},403);
let list=await req('/api/admin?kind=task&q='+prefix,admin);
assert.ok(list.rows.find(r=>r.id===task.id)?.restricted);checks++;
await restore(task.id);
assert.ok((await market(null)).records.some(r=>r.id===task.id));checks++;
await restrict('profile:'+provider.id);
await market(provider,{action:'profile',...common,skills:'Изменённые навыки'});
assert.ok(!(await market(null)).records.some(r=>r.id==='profile:'+provider.id));checks++;
await restore('profile:'+provider.id);
await restrict('account:'+provider.id);
assert.ok((await market(provider)).user.blocked);checks++;
assert.ok(!(await market(null)).records.some(r=>r.id==='profile:'+provider.id));checks++;
await market(provider,{action:'register',name:'Другая роль',role:'customer'},403);
await market(provider,{action:'message',parent:bid.id,description:'Нельзя'},403);

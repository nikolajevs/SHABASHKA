await market(provider,{action:'profile',...common,skills:'Сборка'});
const task=await market(customer,{action:'task',...common});
await market(provider,{action:'bid',parent:task.id,description:'Готов',price:'40 €'});
const bid=(await market(customer)).records.find(r=>r.kind==='bid'&&r.parent===task.id);
